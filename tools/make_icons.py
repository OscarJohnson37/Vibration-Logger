"""Draws the logger's app icon and writes it into the firmware as PNG byte arrays.

The logger's own web page and the master dashboard serve these so a phone can add them to the
home screen with a proper icon (iPhone: apple-touch-icon 180 px; Android: web manifest 192 and
512 px).

    python tools/make_icons.py      # writes firmware/lib/net/src/icons.h, the master dashboard's
                                    # static/icon-*.png, and icon-preview.png

Needs Pillow. Edit the drawing below to restyle it, then rebuild the firmware.
"""

from __future__ import annotations

import io
import math
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware" / "lib" / "net" / "src" / "icons.h"
MASTER_STATIC = ROOT / "master" / "logger_master" / "static"
SIZES = (180, 192, 512)

BG_TOP = (31, 72, 140)       # deep blue
BG_BOTTOM = (18, 40, 84)
WAVE = (255, 255, 255)
LED = (61, 214, 140)         # the green status LED


def draw(size: int) -> Image.Image:
    s = 4  # supersample, then shrink for smooth edges
    n = size * s
    img = Image.new("RGBA", (n, n))
    g = ImageDraw.Draw(img)
    for y in range(n):  # vertical gradient
        t = y / (n - 1)
        g.line([(0, y), (n, y)], fill=tuple(round(a + (b - a) * t) for a, b in zip(BG_TOP, BG_BOTTOM)))
    # Full-bleed square: iOS and Android round the corners themselves

    # Vibration trace: a burst that grows and decays across the middle. Drawn as overlapping
    # dots along the curve: a clean round-capped stroke at any thickness.
    x0, x1, mid, amp, r = 0.15 * n, 0.85 * n, 0.56 * n, 0.22 * n, 0.026 * n
    steps = 3000
    for i in range(steps + 1):
        u = i / steps
        env = math.sin(math.pi * u) ** 1.6
        x = x0 + (x1 - x0) * u
        y = mid - amp * env * math.sin(2 * math.pi * 4.5 * u)
        g.ellipse([x - r, y - r, x + r, y + r], fill=WAVE)

    # Status LED, top right, with a soft glow (its own layer, blended)
    cx, cy, lr = 0.77 * n, 0.23 * n, 0.055 * n
    glow = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    gg = ImageDraw.Draw(glow)
    for k, a in ((2.2, 40), (1.6, 70)):
        gg.ellipse([cx - lr * k, cy - lr * k, cx + lr * k, cy + lr * k], fill=(*LED, a))
    img = Image.alpha_composite(img, glow)
    ImageDraw.Draw(img).ellipse([cx - lr, cy - lr, cx + lr, cy + lr], fill=LED)
    return img.resize((size, size), Image.LANCZOS).convert("RGB")


def png_bytes(img: Image.Image) -> bytes:
    buf = io.BytesIO()
    img.quantize(colors=64, method=Image.Quantize.MEDIANCUT).save(buf, "PNG", optimize=True)
    return buf.getvalue()


def main() -> None:
    lines = [
        "// Generated by tools/make_icons.py: the logger page's home-screen icons (PNG). Don't edit.",
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
        "namespace logger {",
        "",
    ]
    for size in SIZES:
        data = png_bytes(draw(size))
        (MASTER_STATIC / f"icon-{size}.png").write_bytes(data)
        lines.append(f"static const uint8_t ICON_{size}[] PROGMEM = {{")
        for i in range(0, len(data), 20):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
        lines.append("};")
        lines.append("")
        print(f"icon {size}px: {len(data)} bytes")
    lines.append("}  // namespace logger")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    draw(512).save(Path(__file__).with_name("icon-preview.png"))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
